async function seedDatabase() {
  const count = (await db.prepare("SELECT COUNT(*) AS count FROM users").get()).count;
  if (Number(count) !== 0) return;

  const agentEmail = process.env.SEED_CONSULTANT_EMAIL || process.env.SEED_AGENT_EMAIL || null;
  const requestedUsername = (process.env.SEED_CONSULTANT_USERNAME || agentEmail?.split("@")[0] || "superadmin")
    .trim().replace(/[^A-Za-z0-9._-]/g, "").slice(0, 32);
  const agentUsername = /^[A-Za-z0-9][A-Za-z0-9._-]{2,31}$/.test(requestedUsername) ? requestedUsername : "superadmin";
  const agentPassword = process.env.SEED_CONSULTANT_PASSWORD || process.env.SEED_AGENT_PASSWORD || null;
  const contactNumber = process.env.SEED_CONSULTANT_CONTACT_NUMBER?.trim() || null;
  const agentName = process.env.SEED_CONSULTANT_NAME?.trim() || process.env.SEED_AGENT_NAME?.trim() || "Jishnu Infotech Super Admin";
  if (!agentPassword) {
    const message = "No bootstrap Super Admin was created. Set SEED_CONSULTANT_PASSWORD and optionally SEED_CONSULTANT_USERNAME to initialize a fresh database.";
    if (isProduction) throw new Error(message);
    console.warn(message);
    return;
  }
  if (agentPassword.length < 8) {
    throw new Error("The bootstrap Super Admin password must be at least 8 characters.");
  }

  await db.transaction(async () => {
    await db.prepare(`
      INSERT INTO users (name, username, email, contact_number, password_hash, role, is_admin, routing_priority)
      VALUES (?, ?, ?, ?, ?, 'agent', 1, 1) RETURNING id
    `).run(agentName, agentUsername, agentEmail, contactNumber, bcrypt.hashSync(agentPassword, 12));

    await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
  })();
}

async function recoverSuperAdminFromEnvironment() {
  const explicitlyRequested = process.env.RECOVER_SUPER_ADMIN?.trim().toLowerCase() === "true";
  if (process.env.RECOVER_SUPER_ADMIN?.trim().toLowerCase() === "false") return;
  const email = process.env.SEED_CONSULTANT_EMAIL?.trim();
  const username = process.env.SEED_CONSULTANT_USERNAME?.trim();
  const password = process.env.SEED_CONSULTANT_PASSWORD;
  const contactNumber = process.env.SEED_CONSULTANT_CONTACT_NUMBER?.trim() || null;
  const automaticSync = Boolean(username && password);
  if (!explicitlyRequested && !automaticSync) return;
  if ((!email && !username) || !password) {
    console.warn("Super Admin environment login sync skipped because a username/email or password is missing.");
    return;
  }
  if (password.length < 8 || password.length > 128) {
    console.warn("Super Admin environment login sync skipped because the configured password length is invalid.");
    return;
  }
  if (username && !/^[A-Za-z0-9][A-Za-z0-9._-]{2,31}$/.test(username)) {
    console.warn("Super Admin environment login sync skipped because SEED_CONSULTANT_USERNAME is invalid.");
    return;
  }

  const markerKey = automaticSync ? "super_admin_seed_sync_completed" : "super_admin_recovery_completed";
  const completed = await db.prepare("SELECT value FROM workspace_settings WHERE key = ?").get(markerKey);
  if (completed) {
    console.log("Super Admin environment login sync has already completed; no account changes made.");
    return;
  }
  const userCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users").get()).count);
  if (userCount === 0) return;

  // Avoid nullable `? IS NOT NULL` predicates here: PostgreSQL cannot infer
  // the parameter type for those placeholders (SQLSTATE 42P18) during startup.
  const identityPredicates = [];
  const identityValues = [];
  if (username) {
    identityPredicates.push("username = ?");
    identityValues.push(username);
  }
  if (email) {
    identityPredicates.push("lower(email) = lower(?)");
    identityValues.push(email);
  }
  const target = await db.prepare(`SELECT id, role, is_admin, disabled_at FROM users WHERE ${identityPredicates.join(" OR ")}`).get(...identityValues);
  let adminId = null;
  if (target) {
    if (target.role !== "agent" || !target.is_admin || target.disabled_at) {
      console.warn("Super Admin environment login sync skipped because the configured username/email belongs to another account.");
      return;
    }
    adminId = target.id;
  } else {
    const admins = await db.prepare("SELECT id FROM users WHERE role = 'agent' AND is_admin = 1 AND disabled_at IS NULL ORDER BY id").all();
    if (admins.length !== 1) {
      console.warn(`Super Admin environment login sync skipped; expected one active Super Admin, found ${admins.length}.`);
      return;
    }
    adminId = admins[0].id;
  }

  try {
    await db.transaction(async () => {
      await db.prepare("UPDATE users SET username = COALESCE(?, username), email = COALESCE(?, email), contact_number = COALESCE(?, contact_number), password_hash = ? WHERE id = ?")
        .run(username || null, email || null, contactNumber, bcrypt.hashSync(password, 12), adminId);
      await db.prepare("INSERT INTO workspace_settings (key, value) VALUES (?, ?)")
        .run(markerKey, new Date().toISOString());
    })();
  } catch (error) {
    console.error("Super Admin environment login sync failed; the portal will continue starting:", error.message);
    return;
  }
  console.log(`Super Admin environment login synchronized for username: ${username || "unchanged"}.`);
}

export async function initializeSchema() {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS schema_migrations (
      version INTEGER PRIMARY KEY,
      applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    )
  `);

  const latestCodeVersion = schemaMigrations.at(-1)?.version || 0;
  await db.transaction(async () => {
    await db.exec("LOCK TABLE schema_migrations IN EXCLUSIVE MODE");
    const current = await db.prepare("SELECT COALESCE(MAX(version), 0) AS version FROM schema_migrations").get();
    if (Number(current.version) > latestCodeVersion) {
      throw new Error(`Database schema version ${current.version} is newer than this application supports (${latestCodeVersion}).`);
    }

    for (const migration of schemaMigrations) {
      if (migration.version <= Number(current.version)) continue;
      await migration.apply();
      await db.prepare("INSERT INTO schema_migrations (version) VALUES (?)").run(migration.version);
    }
  })();
}

export async function initializeDatabase() {
  await initializeSchema();
  await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
  const unassignedClientCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE role = 'customer' AND company_id IS NULL").get()).count);
  let legacyCompanyId = null;
  if (unassignedClientCount > 0) {
    const legacyCompany = await db.prepare(`
      INSERT INTO companies (name, slug) VALUES ('Existing Customers', 'existing-customers')
      ON CONFLICT (slug) DO NOTHING RETURNING id
    `).run();
    const existingCompany = legacyCompany.lastInsertRowid
      ? { id: legacyCompany.lastInsertRowid }
      : await db.prepare("SELECT id FROM companies WHERE slug = 'existing-customers'").get();
    legacyCompanyId = existingCompany.id;
    await db.prepare("UPDATE users SET company_id = ? WHERE role = 'customer' AND company_id IS NULL").run(legacyCompanyId);
    await db.prepare(`
      INSERT INTO company_memberships (user_id, company_id, is_company_admin)
      SELECT id, company_id, is_company_admin FROM users WHERE role = 'customer' AND company_id = ?
      ON CONFLICT (user_id, company_id) DO NOTHING
    `).run(legacyCompanyId);
  }
  await db.prepare(`
    UPDATE tickets SET company_id = (
      SELECT company_id FROM users WHERE users.id = tickets.customer_id
    ) WHERE company_id IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET resolved_at = updated_at
    WHERE status = 'resolved' AND resolved_at IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET first_response_at = (
      SELECT MIN(m.created_at)
      FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
    WHERE first_response_at IS NULL AND EXISTS (
      SELECT 1 FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
  `).run();

  const agentPriorities = await db.prepare("SELECT id, routing_priority FROM users WHERE role = 'agent' ORDER BY routing_priority, id").all();
  if (agentPriorities.length && agentPriorities.every((agent) => agent.routing_priority === 0)) {
    await db.transaction(async () => {
      for (const [index, agent] of agentPriorities.entries()) {
        await db.prepare("UPDATE users SET routing_priority = ? WHERE id = ?").run(index + 1, agent.id);
      }
    })();
  }

  if (legacyCompanyId !== null) {
    const companyAdminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM company_memberships WHERE company_id = ? AND is_company_admin = 1").get(legacyCompanyId)).count);
    if (companyAdminCount === 0) {
      const firstClient = await db.prepare("SELECT id FROM users WHERE role = 'customer' AND company_id = ? ORDER BY id LIMIT 1").get(legacyCompanyId);
      if (firstClient) await db.prepare("UPDATE company_memberships SET is_company_admin = 1 WHERE user_id = ? AND company_id = ?").run(firstClient.id, legacyCompanyId);
    }
  }
  const legacyAssignments = await db.prepare(`
    SELECT t.id, t.assignee_id, t.created_at FROM tickets t
    WHERE t.assignee_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM ticket_assignment_history h WHERE h.ticket_id = t.id AND h.source = 'migration'
    )
  `).all();
  for (const ticket of legacyAssignments) {
    await db.prepare("INSERT INTO ticket_assignment_history (ticket_id, agent_id, source, created_at) VALUES (?, ?, 'migration', ?)").run(ticket.id, ticket.assignee_id, ticket.created_at);
  }

  const adminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE is_admin = 1").get()).count);
  if (adminCount === 0) {
    const firstAgent = await db.prepare("SELECT id FROM users WHERE role = 'agent' ORDER BY id LIMIT 1").get();
    if (firstAgent) await db.prepare("UPDATE users SET is_admin = 1 WHERE id = ?").run(firstAgent.id);
  }

  await recoverSuperAdminFromEnvironment();
  await seedDatabase();
}

export async function closeDatabase() {
  await db.close();
}
