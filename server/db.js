async function seedDatabase() {
  const count = (await db.prepare("SELECT COUNT(*) AS count FROM users").get()).count;
  if (Number(count) !== 0) return;

  const agentEmail = process.env.SEED_AGENT_EMAIL || (isProduction ? null : "alex@relaysupport.test");
  const agentPassword = process.env.SEED_AGENT_PASSWORD || (isProduction ? null : "Support123!");
  const customerEmail = process.env.SEED_CUSTOMER_EMAIL || (isProduction ? null : "sam@northstar.test");
  const customerPassword = process.env.SEED_CUSTOMER_PASSWORD || (isProduction ? null : "Customer123!");
  const agentName = process.env.SEED_AGENT_NAME?.trim() || (isProduction ? "Jishnu Infotech Admin" : "Alex Morgan");
  const customerName = process.env.SEED_CUSTOMER_NAME?.trim() || (isProduction ? "Company Administrator" : "Sam Rivera");
  if (!agentEmail || !agentPassword || !customerEmail || !customerPassword) {
    throw new Error("Set SEED_AGENT_EMAIL, SEED_AGENT_PASSWORD, SEED_CUSTOMER_EMAIL, and SEED_CUSTOMER_PASSWORD before first production startup.");
  }
  if (isProduction && (agentPassword.length < 12 || customerPassword.length < 12)) {
    throw new Error("Production seed passwords must each be at least 12 characters.");
  }

  await db.transaction(async () => {
    const company = await db.prepare("SELECT id FROM companies WHERE slug = 'existing-customers'").get();
    const companyId = company.id;
    const agent = await db.prepare(`
      INSERT INTO users (name, email, password_hash, role, is_admin, routing_priority)
      VALUES (?, ?, ?, 'agent', 1, 1) RETURNING id
    `).run(agentName, agentEmail, bcrypt.hashSync(agentPassword, 12));
    const customer = await db.prepare(`
      INSERT INTO users (name, email, password_hash, role, company_id, is_company_admin)
      VALUES (?, ?, ?, 'customer', ?, 1) RETURNING id
    `).run(customerName, customerEmail, bcrypt.hashSync(customerPassword, 12), companyId);

    await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
    if (isProduction) return;

    const examples = [
      ["Unable to access my account", "I reset my password but still cannot sign in. Could you help me check what is going on?", "open", "high", "portal", -22, "Thanks for letting us know. We are checking this for you now.", -18],
      ["Question about my latest invoice", "Could you help me understand the additional charge on this month's invoice?", "in_progress", "normal", "email", -180, "I am reviewing the invoice details and will follow up shortly.", -120],
      ["Feature request: export reports", "It would be useful to export the monthly report as a CSV file.", "waiting", "low", "portal", -1440, "Thanks for the suggestion. Is there a particular report you need first?", -1200],
      ["Order confirmation not received", "I placed an order yesterday but have not received a confirmation email.", "resolved", "normal", "email", -2880, "We found your order and resent the confirmation. Please check your inbox.", -1440],
    ];
    for (const [subject, description, status, priority, source, age, reply, replyAge] of examples) {
      const createdAt = new Date(Date.now() + age * 60_000).toISOString();
      const repliedAt = new Date(Date.now() + replyAge * 60_000).toISOString();
      const ticket = await db.prepare(`
        INSERT INTO tickets (subject, description, status, priority, customer_id, company_id, assignee_id, source, created_at, updated_at, resolved_at, resolved_by)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) RETURNING id
      `).run(subject, description, status, priority, customer.lastInsertRowid, companyId, agent.lastInsertRowid, source, createdAt, repliedAt, status === "resolved" ? repliedAt : null, status === "resolved" ? agent.lastInsertRowid : null);
      await db.prepare("INSERT INTO messages (ticket_id, author_id, body, created_at) VALUES (?, ?, ?, ?), (?, ?, ?, ?)").run(
        ticket.lastInsertRowid, customer.lastInsertRowid, description, createdAt,
        ticket.lastInsertRowid, agent.lastInsertRowid, reply, repliedAt,
      );
      await db.prepare("INSERT INTO ticket_assignment_history (ticket_id, agent_id, source, created_at) VALUES (?, ?, 'migration', ?)").run(ticket.lastInsertRowid, agent.lastInsertRowid, createdAt);
    }
  })();
}

export async function initializeSchema() {
  await db.exec(schema);
}

export async function initializeDatabase() {
  await initializeSchema();
  await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
  const databaseWasEmpty = Number((await db.prepare("SELECT COUNT(*) AS count FROM users").get()).count) === 0;
  const legacyCompany = await db.prepare(`
    INSERT INTO companies (name, slug) VALUES (?, 'existing-customers')
    ON CONFLICT (slug) DO NOTHING RETURNING id
  `).run(isProduction && databaseWasEmpty ? process.env.SEED_CUSTOMER_COMPANY?.trim() || "Initial Client Company" : "Existing Customers");
  const existingCompany = legacyCompany.lastInsertRowid
    ? { id: legacyCompany.lastInsertRowid }
    : await db.prepare("SELECT id FROM companies WHERE slug = 'existing-customers'").get();
  const legacyCompanyId = existingCompany.id;

  await db.prepare("UPDATE users SET company_id = ? WHERE role = 'customer' AND company_id IS NULL").run(legacyCompanyId);
  await db.prepare(`
    UPDATE tickets SET company_id = (
      SELECT company_id FROM users WHERE users.id = tickets.customer_id
    ) WHERE company_id IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET resolved_at = updated_at
    WHERE status = 'resolved' AND resolved_at IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET first_response_at = (
      SELECT MIN(m.created_at)
      FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
    WHERE first_response_at IS NULL AND EXISTS (
      SELECT 1 FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
  `).run();

  const agentPriorities = await db.prepare("SELECT id, routing_priority FROM users WHERE role = 'agent' ORDER BY routing_priority, id").all();
  if (agentPriorities.length && agentPriorities.every((agent) => agent.routing_priority === 0)) {
    await db.transaction(async () => {
      for (const [index, agent] of agentPriorities.entries()) {
        await db.prepare("UPDATE users SET routing_priority = ? WHERE id = ?").run(index + 1, agent.id);
      }
    })();
  }

  const companyAdminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE company_id = ? AND is_company_admin = 1").get(legacyCompanyId)).count);
  if (companyAdminCount === 0) {
    const firstClient = await db.prepare("SELECT id FROM users WHERE role = 'customer' AND company_id = ? ORDER BY id LIMIT 1").get(legacyCompanyId);
    if (firstClient) await db.prepare("UPDATE users SET is_company_admin = 1 WHERE id = ?").run(firstClient.id);
  }
  const legacyAssignments = await db.prepare(`
    SELECT t.id, t.assignee_id, t.created_at FROM tickets t
    WHERE t.assignee_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM ticket_assignment_history h WHERE h.ticket_id = t.id AND h.source = 'migration'
    )
  `).all();
  for (const ticket of legacyAssignments) {
    await db.prepare("INSERT INTO ticket_assignment_history (ticket_id, agent_id, source, created_at) VALUES (?, ?, 'migration', ?)").run(ticket.id, ticket.assignee_id, ticket.created_at);
  }

  const adminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE is_admin = 1").get()).count);
  if (adminCount === 0) {
    const firstAgent = await db.prepare("SELECT id FROM users WHERE role = 'agent' ORDER BY id LIMIT 1").get();
    if (firstAgent) await db.prepare("UPDATE users SET is_admin = 1 WHERE id = ?").run(firstAgent.id);
  }

  await seedDatabase();
}

export async function closeDatabase() {
  await db.close();
}
