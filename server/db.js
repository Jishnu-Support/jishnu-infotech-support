// Version 1 records the schema already used by existing deployments. Since
// every statement is idempotent, it safely establishes the baseline on both
// fresh databases and databases created before migration tracking existed.
// Add future schema changes as new, append-only entries; do not edit a version
// after it has been applied to a production database.
const schemaMigrations = [
  { version: 1, apply: () => db.exec(schema) },
  { version: 2, apply: () => db.exec(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS specialty TEXT NOT NULL DEFAULT 'both'
      CHECK (specialty IN ('functional', 'technical', 'both'));
    ALTER TABLE agent_invitations ADD COLUMN IF NOT EXISTS specialty TEXT NOT NULL DEFAULT 'both'
      CHECK (specialty IN ('functional', 'technical', 'both'));
  `) },
  { version: 3, apply: () => db.exec(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS contact_number TEXT;
  `) },
  { version: 4, apply: () => db.exec(`
    ALTER TABLE companies ADD COLUMN IF NOT EXISTS support_valid_until DATE;
  `) },
];

async function seedDatabase() {
  const count = (await db.prepare("SELECT COUNT(*) AS count FROM users").get()).count;
  if (Number(count) !== 0) return;

  const agentEmail = process.env.SEED_CONSULTANT_EMAIL || process.env.SEED_AGENT_EMAIL || null;
  const agentPassword = process.env.SEED_CONSULTANT_PASSWORD || process.env.SEED_AGENT_PASSWORD || null;
  const contactNumber = process.env.SEED_CONSULTANT_CONTACT_NUMBER?.trim();
  const agentName = process.env.SEED_CONSULTANT_NAME?.trim() || process.env.SEED_AGENT_NAME?.trim() || "Jishnu Infotech Super Admin";
  if (!agentEmail || !agentPassword || !contactNumber) {
    const message = "No bootstrap Super Admin was created. Set SEED_CONSULTANT_EMAIL, SEED_CONSULTANT_PASSWORD, and SEED_CONSULTANT_CONTACT_NUMBER to initialize a fresh database.";
    if (isProduction) throw new Error(message);
    console.warn(message);
    return;
  }
  if (agentPassword.length < 12) {
    throw new Error("The bootstrap Super Admin password must be at least 12 characters.");
  }

  await db.transaction(async () => {
    await db.prepare(`
      INSERT INTO users (name, email, contact_number, password_hash, role, is_admin, routing_priority)
      VALUES (?, ?, ?, ?, 'agent', 1, 1) RETURNING id
    `).run(agentName, agentEmail, contactNumber, bcrypt.hashSync(agentPassword, 12));

    await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
  })();
}

export async function initializeSchema() {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS schema_migrations (
      version INTEGER PRIMARY KEY,
      applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    )
  `);

  const latestCodeVersion = schemaMigrations.at(-1)?.version || 0;
  await db.transaction(async () => {
    await db.exec("LOCK TABLE schema_migrations IN EXCLUSIVE MODE");
    const current = await db.prepare("SELECT COALESCE(MAX(version), 0) AS version FROM schema_migrations").get();
    if (Number(current.version) > latestCodeVersion) {
      throw new Error(`Database schema version ${current.version} is newer than this application supports (${latestCodeVersion}).`);
    }

    for (const migration of schemaMigrations) {
      if (migration.version <= Number(current.version)) continue;
      await migration.apply();
      await db.prepare("INSERT INTO schema_migrations (version) VALUES (?)").run(migration.version);
    }
  })();
}

export async function initializeDatabase() {
  await initializeSchema();
  await db.prepare("INSERT INTO workspace_settings (key, value) VALUES ('sla_first_response_hours', '4'), ('sla_resolution_hours', '48') ON CONFLICT DO NOTHING").run();
  const unassignedClientCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE role = 'customer' AND company_id IS NULL").get()).count);
  let legacyCompanyId = null;
  if (unassignedClientCount > 0) {
    const legacyCompany = await db.prepare(`
      INSERT INTO companies (name, slug) VALUES ('Existing Customers', 'existing-customers')
      ON CONFLICT (slug) DO NOTHING RETURNING id
    `).run();
    const existingCompany = legacyCompany.lastInsertRowid
      ? { id: legacyCompany.lastInsertRowid }
      : await db.prepare("SELECT id FROM companies WHERE slug = 'existing-customers'").get();
    legacyCompanyId = existingCompany.id;
    await db.prepare("UPDATE users SET company_id = ? WHERE role = 'customer' AND company_id IS NULL").run(legacyCompanyId);
  }
  await db.prepare(`
    UPDATE tickets SET company_id = (
      SELECT company_id FROM users WHERE users.id = tickets.customer_id
    ) WHERE company_id IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET resolved_at = updated_at
    WHERE status = 'resolved' AND resolved_at IS NULL
  `).run();
  await db.prepare(`
    UPDATE tickets SET first_response_at = (
      SELECT MIN(m.created_at)
      FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
    WHERE first_response_at IS NULL AND EXISTS (
      SELECT 1 FROM messages m JOIN users u ON u.id = m.author_id
      WHERE m.ticket_id = tickets.id AND u.role = 'agent' AND m.created_at >= tickets.created_at
    )
  `).run();

  const agentPriorities = await db.prepare("SELECT id, routing_priority FROM users WHERE role = 'agent' ORDER BY routing_priority, id").all();
  if (agentPriorities.length && agentPriorities.every((agent) => agent.routing_priority === 0)) {
    await db.transaction(async () => {
      for (const [index, agent] of agentPriorities.entries()) {
        await db.prepare("UPDATE users SET routing_priority = ? WHERE id = ?").run(index + 1, agent.id);
      }
    })();
  }

  if (legacyCompanyId !== null) {
    const companyAdminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE company_id = ? AND is_company_admin = 1").get(legacyCompanyId)).count);
    if (companyAdminCount === 0) {
      const firstClient = await db.prepare("SELECT id FROM users WHERE role = 'customer' AND company_id = ? ORDER BY id LIMIT 1").get(legacyCompanyId);
      if (firstClient) await db.prepare("UPDATE users SET is_company_admin = 1 WHERE id = ?").run(firstClient.id);
    }
  }
  const legacyAssignments = await db.prepare(`
    SELECT t.id, t.assignee_id, t.created_at FROM tickets t
    WHERE t.assignee_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM ticket_assignment_history h WHERE h.ticket_id = t.id AND h.source = 'migration'
    )
  `).all();
  for (const ticket of legacyAssignments) {
    await db.prepare("INSERT INTO ticket_assignment_history (ticket_id, agent_id, source, created_at) VALUES (?, ?, 'migration', ?)").run(ticket.id, ticket.assignee_id, ticket.created_at);
  }

  const adminCount = Number((await db.prepare("SELECT COUNT(*) AS count FROM users WHERE is_admin = 1").get()).count);
  if (adminCount === 0) {
    const firstAgent = await db.prepare("SELECT id FROM users WHERE role = 'agent' ORDER BY id LIMIT 1").get();
    if (firstAgent) await db.prepare("UPDATE users SET is_admin = 1 WHERE id = ?").run(firstAgent.id);
  }

  await seedDatabase();
}

export async function closeDatabase() {
  await db.close();
}
