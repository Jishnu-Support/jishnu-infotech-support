import "dotenv/config";
import bcrypt from "bcryptjs";
import pg from "pg";
import { AsyncLocalStorage } from "node:async_hooks";

const { Pool, types } = pg;
const isProduction = process.env.NODE_ENV === "production";
const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error("DATABASE_URL must be set to a PostgreSQL connection string.");
}

types.setTypeParser(20, Number);
types.setTypeParser(1114, (value) => value);

const pool = new Pool({
  connectionString,
  options: "-c timezone=UTC",
  ssl: process.env.PG_SSL === "true" ? { rejectUnauthorized: true } : undefined,
  max: Number(process.env.PG_POOL_MAX || 10),
});
const transactionContext = new AsyncLocalStorage();

function postgresSql(sql, returningId = false) {
  const ignoreConflict = /^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(sql);
  let statement = sql.trim().replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/i, "INSERT INTO");
  statement = statement.replace(/\s+COLLATE\s+NOCASE\b/gi, "");
  statement = statement.replace(/\bdatetime\(([^)]+)\)/gi, "($1::timestamptz)");
  statement = statement.replace(/\bsubstr\(([^,]+),\s*1,\s*10\)/gi, "TO_CHAR(($1)::timestamp, 'YYYY-MM-DD')");
  statement = statement.replace(/\bMAX\(email_cursors\.last_uid,\s*excluded\.last_uid\)/gi, "GREATEST(email_cursors.last_uid, excluded.last_uid)");
  statement = statement.replace(/\bAS\s+([A-Za-z_][A-Za-z0-9_]*[A-Z][A-Za-z0-9_]*)\b/g, 'AS "$1"');

  let parameterIndex = 0;
  statement = statement.replace(/\?/g, () => `$${++parameterIndex}`);

  if (ignoreConflict) statement += " ON CONFLICT DO NOTHING";
  if (/^INSERT\s+INTO\b/i.test(statement)
    && !/\bRETURNING\b/i.test(statement)
    && !/\bON\s+CONFLICT\b/i.test(statement)
    && returningId) {
    statement += " RETURNING *";
  }
  return statement;
}

function currentExecutor() {
  return transactionContext.getStore() || pool;
}

function prepare(sql) {
  return {
    async get(...params) {
      const result = await currentExecutor().query(postgresSql(sql), params);
      return result.rows[0];
    },
    async all(...params) {
      const result = await currentExecutor().query(postgresSql(sql), params);
      return result.rows;
    },
    async run(...params) {
      const isInsert = /^\s*INSERT\b/i.test(sql);
      const result = await currentExecutor().query(postgresSql(sql, isInsert), params);
      return { lastInsertRowid: result.rows[0]?.id, changes: result.rowCount };
    },
  };
}

export const db = {
  prepare,
  async exec(sql) {
    await currentExecutor().query(sql);
  },
  transaction(callback) {
    return async (...args) => {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const result = await transactionContext.run(client, () => callback(...args));
        await client.query("COMMIT");
        return result;
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    };
  },
  async close() {
    await pool.end();
  },
};

